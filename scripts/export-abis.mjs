// Exports each contract's ABI from Foundry's build output to `shared/abis/<Name>.ts`
// as an `as const` array, so the TS/front-end side gets fully-typed ABIs.
//
// Run after `forge build`:  node scripts/export-abis.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const CONTRACTS = [
  "DonationLedger",
  "SignatoryRegistry",
  "CaseWorkflow",
  "PeriodAnchor",
  "IntegrityMonitor",
  // interfaces are handy for the client too
  "IDonationLedger",
  "ISignatoryRegistry",
  "ICaseWorkflow",
  "IPeriodAnchor",
  "IIntegrityMonitor",
];

const outDir = resolve(root, "shared", "abis");
mkdirSync(outDir, { recursive: true });

const index = [];
for (const name of CONTRACTS) {
  const artifact = resolve(root, "out", `${name}.sol`, `${name}.json`);
  let abi;
  try {
    abi = JSON.parse(readFileSync(artifact, "utf8")).abi;
  } catch {
    console.warn(`skip ${name}: artifact not found (did you run \`forge build\`?)`);
    continue;
  }
  const ts =
    `// AUTO-GENERATED by scripts/export-abis.mjs — do not edit.\n` +
    `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(resolve(outDir, `${name}.ts`), ts);
  index.push(`export { ${name}Abi } from "./${name}";`);
  console.log(`wrote shared/abis/${name}.ts`);
}
writeFileSync(resolve(outDir, "index.ts"), index.join("\n") + "\n");
console.log(`wrote shared/abis/index.ts (${index.length} ABIs)`);
